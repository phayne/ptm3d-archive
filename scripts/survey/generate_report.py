def embed_image(path, quality=92):
    """Read an image and return HTML img tag with base64-encoded JPEG."""
    if not Path(path).exists():
        return f"<p><em>Image not found: {path}</em></p>"
    from PIL import Image
    from io import BytesIO
    img = Image.open(path)
    if img.mode in ('RGBA', 'P'):
        bg = Image.new('RGB', img.size, (255,255,255))
        if img.mode == 'RGBA': bg.paste(img, mask=img.split()[3])
        else: bg.paste(img)
        img = bg
    elif img.mode != 'RGB':
        img = img.convert('RGB')
    buf = BytesIO()
    img.save(buf, format='JPEG', quality=quality, optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode('ascii')
    return f'<img src="data:image/jpeg;base64,{b64}" alt="{Path(path).stem}">'


def build_sites_table(cfg):
    """Build HTML table of selected sites."""
    rows = []
    if cfg.locations_csv.exists():
        illum_frac = None
        max_cont = None
        summer_tmax = None
        frac_file = cfg.survey_dir / "illum_total_fraction.bin"
        hours_file = cfg.survey_dir / "illum_max_continuous_hours.bin"
        if frac_file.exists(): illum_frac = read_stats_binary(str(frac_file))
        if hours_file.exists(): max_cont = read_stats_binary(str(hours_file))
        for lun in cfg.thermal.lunations:
            tfile = cfg.thermal_dir / f"lunation_{lun:02d}/statistics/temperature_max.bin"
            if tfile.exists():
                summer_tmax = read_stats_binary(str(tfile))
                break

        # Read mesh for face lookup
        from utils import read_ply_mesh
        _, _, _, lats, lons = read_ply_mesh(str(cfg.mesh_path))
        import numpy as np

        with open(cfg.locations_csv) as f:
            for line in f:
                if line.startswith('#') or not line.strip(): continue
                p = line.strip().split(',')
                if len(p) < 3: continue
                name, lat, lon = p[0], float(p[1]), float(p[2])
                fidx = int(np.argmin((lats-lat)**2 + (lons-lon)**2))
                frac = f"{illum_frac[fidx]*100:.1f}" if illum_frac is not None else "—"
                hrs = f"{max_cont[fidx]:.0f}" if max_cont is not None else "—"
                tmax = f"{summer_tmax[fidx]:.0f}" if summer_tmax is not None else "—"
                rows.append(f"<tr><td>{name}</td><td>{abs(lat):.2f}</td><td>{lon:.2f}</td>"
                           f"<td>{frac}</td><td>{hrs}</td><td>{tmax}</td></tr>")

    header = ("<table><tr><th>Site</th><th>Lat (°S)</th><th>Lon (°E)</th>"
              "<th>Illum (%)</th><th>Max Cont. (hr)</th><th>T_max (K)</th></tr>")
    return header + '\n'.join(rows) + "</table>"


def build_timing_table(cfg):
    """Build illumination/shadow timing table."""
    if not cfg.locations_csv.exists():
        return ""

    from utils import read_ply_mesh
    import numpy as np
    _, _, _, lats, lons = read_ply_mesh(str(cfg.mesh_path))
    nf = len(lats)
    n_lun = cfg.illumination.num_lunations
    lunation_dates = [cfg.time.start_datetime + __import__('datetime').timedelta(days=i*cfg.time.lunation_days)
                      for i in range(n_lun)]

    html = "<h2>Illumination/Shadow Timing</h2>\n"
    html += '<table><tr><th>Site</th><th>State</th><th>Start (UTC)</th><th>End (UTC)</th><th>Duration (lunations)</th></tr>\n'

    with open(cfg.locations_csv) as f:
        for line in f:
            if line.startswith('#') or not line.strip(): continue
            p = line.strip().split(',')
            if len(p) < 3: continue
            name, lat, lon = p[0], float(p[1]), float(p[2])
            fidx = int(np.argmin((lats-lat)**2 + (lons-lon)**2))

            states = []
            for i in range(n_lun):
                sf = cfg.survey_dir / f"lunation_{i:02d}/statistics/direct_solar_avg.bin"
                if sf.exists():
                    avg = read_stats_binary(str(sf))
                    states.append(len(avg)==nf and avg[fidx] > 0)
                else:
                    states.append(False)

            # Find transitions
            lit_start = dark_start = None
            windows = []
            for i in range(n_lun):
                if states[i] and lit_start is None:
                    lit_start = i
                    if dark_start is not None:
                        windows.append(('Shadow', dark_start, i))
                        dark_start = None
                elif not states[i] and dark_start is None:
                    dark_start = i
                    if lit_start is not None:
                        windows.append(('Illuminated', lit_start, i))
                        lit_start = None
            if lit_start is not None: windows.append(('Illuminated', lit_start, n_lun))
            if dark_start is not None: windows.append(('Shadow', dark_start, n_lun))

            first_row = True
            for state, start, end in windows:
                cls = 'lit' if state == 'Illuminated' else 'dark'
                site_cell = f'<td rowspan="{len(windows)}">{name}</td>' if first_row else ''
                html += (f'<tr class="{cls}">{site_cell}'
                        f'<td>{state}</td>'
                        f'<td>{lunation_dates[start].strftime("%Y-%m-%d")}</td>'
                        f'<td>{lunation_dates[min(end, n_lun-1)].strftime("%Y-%m-%d")}</td>'
                        f'<td>{end-start}</td></tr>\n')
                first_row = False

    html += "</table>"
    return html


def build_traverse_section(cfg):
    """Build traverse results section."""
    result_file = Path(cfg.output.base_dir) / "traverse_result.json"
    if not result_file.exists():
        return ""

    with open(result_file) as f:
        result = json.load(f)

    html = "<h2>Traverse Plan</h2>\n"
    html += (f"<p>Total distance: {result['total_distance_km']:.1f} km | "
             f"Duration: {result['total_duration_days']:.1f} days | "
             f"Sites visited: {result['sites_visited']}</p>\n")
    html += '<table><tr><th>Arrive (UTC)</th><th>Site</th><th>Lat (°S)</th><th>Lon (°E)</th><th>+Distance (km)</th></tr>\n'
    for stop in result['schedule']:
        html += (f"<tr><td>{stop['arrive'][:16]}</td><td>{stop['site']}</td>"
                f"<td>{abs(stop['lat']):.2f}</td><td>{stop['lon']:.2f}</td>"
                f"<td>{stop['dist_from_prev']:.1f}</td></tr>\n")
    html += "</table>"
    return html


def generate_report(cfg: SurveyConfig, compact=False) -> bool:
    """Generate HTML report from survey results."""
    print("=== Generating Report ===")
    fig_dir = cfg.figures_dir

    state = load_state(cfg.state_file)
    n_faces = state.get('mesh', {}).get('faces', 0)

    # Temperature section
    temp_html = ""
    temp_pairs = []
    for lun, label in [(cfg.thermal.lunations[0] if cfg.thermal.lunations else 7, 'Summer'),
                        (cfg.thermal.lunations[-1] if len(cfg.thermal.lunations) > 1 else 13, 'Winter')]:
        for stat in ['avg', 'max']:
            p = fig_dir / f"temp_{label.lower()}_{stat}.png"
            if p.exists():
                temp_pairs.append((label, stat, p))

    if temp_pairs:
        temp_html = "<h2>Surface Temperature</h2>\n"
        for label, stat, p in temp_pairs:
            q = 75 if compact else 92
            temp_html += f"<h3>{label} {stat.title()} Temperature</h3>\n{embed_image(str(p), q)}\n"

    sel = cfg.selection
    end_date = (cfg.time.start_datetime +
                __import__('datetime').timedelta(days=cfg.illumination.num_lunations * cfg.time.lunation_days))

    q = 75 if compact else 92
    html = HTML_TEMPLATE.format(
        title=f"Polar Survey: {cfg.name}",
        n_faces=n_faces,
        start_time=cfg.time.start[:10],
        end_time=end_date.strftime('%Y-%m-%d'),
        n_lunations=cfg.illumination.num_lunations,
        gen_time=datetime.now().strftime('%Y-%m-%d %H:%M'),
        classification_img=embed_image(str(fig_dir/'classification.png'), q),
        illum_fraction_img=embed_image(str(fig_dir/'illum_fraction.png'), q),
        continuous_duration_img=embed_image(str(fig_dir/'continuous_duration.png'), q),
        seasonal_pattern_img=embed_image(str(fig_dir/'seasonal_pattern.png'), q),
        temperature_section=temp_html,
        min_illum=sel.min_illum_fraction*100,
        max_illum=sel.max_illum_fraction*100,
        min_hours=sel.min_continuous_hours,
        max_temp=sel.max_temperature_K,
        sites_table=build_sites_table(cfg),
        timing_table_section=build_timing_table(cfg),
        traverse_section=build_traverse_section(cfg),
        body=cfg.body.upper(),
        ks=cfg.thermophysical.ks,
        kd=cfg.thermophysical.kd,
        equil=cfg.thermal.equilibration_orbits,
        rad_iter=cfg.thermal.max_coupling_iterations,
        dem_res="20 m/px",
    )

    suffix = "_compact" if compact else ""
    report_path = Path(cfg.output.base_dir) / f"report{suffix}.html"
    with open(report_path, 'w') as f:
        f.write(html)

    import os
    size_mb = os.path.getsize(report_path) / 1e6
    print(f"  Report: {report_path} ({size_mb:.1f} MB)")
    return True


if __name__ == '__main__':
    if len(sys.argv) < 2:
        print("Usage: python generate_report.py <config.yaml> [--compact]")
        sys.exit(1)
    cfg = load_config(sys.argv[1])
    compact = '--compact' in sys.argv
    generate_report(cfg, compact)
